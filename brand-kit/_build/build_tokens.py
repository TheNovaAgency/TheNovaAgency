#!/usr/bin/env python3
"""Build tokens.css / tokens.json / tailwind.preset.js from the theme blocks in nova.css.
Usage: python build_tokens.py <path/to/nova.css> <brand-kit dir>"""
import json, os, re, sys

css_src, kit = sys.argv[1], sys.argv[2]
src = open(css_src).read()
blocks = {}
for name in ("dark", "light"):
    m = re.search(r"\.nv-%s\{(.*?)\}" % name, src, re.S)
    blocks[name] = m.group(1).strip()

def parse(block):
    out = {}
    for decl in block.replace("\n", "").split(";"):
        decl = decl.strip()
        if decl.startswith("--"):
            k, v = decl.split(":", 1); out[k[2:]] = v.strip()
    return out
dark, light = parse(blocks["dark"]), parse(blocks["light"])

CORE = {"ink": "#0A0607", "ignition": "#FF4B2B", "ignition-deep": "#C42A0E", "bone": "#F4EDE8",
        "paper": "#F7F3F0", "ember": "#FFB547", "ember-deep": "#8A5300"}
SANS = "'Space Grotesk', ui-sans-serif, system-ui, sans-serif"
MONO = "'JetBrains Mono', ui-monospace, SFMono-Regular, Menlo, monospace"
SCALE = [  # name, family, size, line-height, tracking(em), weight, transform
    ("display-xl", "sans", 120, 0.92, -0.03, 600, None),
    ("display", "sans", 88, 0.96, -0.03, 600, None),
    ("h1", "sans", 56, 1.0, -0.03, 600, None),
    ("h2", "sans", 36, 1.08, -0.02, 600, None),
    ("h3", "sans", 22, 1.2, -0.01, 600, None),
    ("lead", "sans", 20, 1.5, 0, 400, None),
    ("body", "sans", 16, 1.6, 0, 400, None),
    ("small", "mono", 13, 1.65, 0, 400, None),
    ("label", "mono", 11, 1.4, 0.2, 400, "uppercase"),
]
SPACE = [4, 8, 12, 16, 24, 32, 48, 64, 96]
RADIUS = {"none": "0", "sm": "2px", "full": "9999px"}
EASE = "cubic-bezier(0.16, 1, 0.3, 1)"
DUR = {"fast": 120, "base": 250, "slow": 400, "slower": 800}

def tr(v): return "0" if v == 0 else f"{v:g}em"

# ---------- tokens.css ----------
def vars_block(d, indent="  "):
    return "\n".join(f"{indent}--{k}:{v};" for k, v in d.items() if k != "color-scheme")

static = ["  /* Core palette */"] + [f"  --nv-{k}:{v};" for k, v in CORE.items()]
static += ["", "  /* Type */", f"  --font-sans:{SANS};", f"  --font-mono:{MONO};"]
for n, fam, size, lh, t, w, tt in SCALE:
    static.append(f"  --text-{n}:{size}px; --leading-{n}:{lh:g}; --tracking-{n}:{tr(t)};")
static += ["", "  /* Space, radius, motion */"] + [f"  --space-{i+1}:{v}px;" for i, v in enumerate(SPACE)]
static += [f"  --radius-{k}:{v};" for k, v in RADIUS.items()]
static += [f"  --ease-out:{EASE};"] + [f"  --duration-{k}:{v}ms;" for k, v in DUR.items()]

css = f"""/* NOVA brand tokens (Ignition v1.0). Generated by _build/build_tokens.py from nova.css.
   Default theme is dark. The OS light preference switches to light unless the page sets
   data-theme="dark"; data-theme="light" / "dark" on <html> always wins.
   .nv-dark / .nv-light are kept verbatim for scoping a theme to any element. */

:root{{
{chr(10).join(static)}
}}

/* Dark (default) */
:root,[data-theme="dark"]{{
{vars_block(dark)}
  color-scheme:dark;
}}

/* Light, from the OS preference */
@media (prefers-color-scheme: light){{
  :root:not([data-theme="dark"]){{
{vars_block(light, "    ")}
    color-scheme:light;
  }}
}}

/* Light, forced */
[data-theme="light"]{{
{vars_block(light)}
  color-scheme:light;
}}

/* Scoped theme classes (verbatim from nova.css) */
.nv-dark{{
  {blocks["dark"]}
}}
.nv-light{{
  {blocks["light"]}
}}
"""
open(os.path.join(kit, "tokens", "tokens.css"), "w").write(css)

# ---------- tokens.json (W3C DTCG-style) ----------
def color(v):
    return {"$type": "color", "$value": v}
def themed(d):
    return {k: color(v) for k, v in d.items() if k != "color-scheme"}
tokens = {
    "$description": "NOVA / The Nova Agency design tokens, Ignition v1.0. DTCG format.",
    "color": {
        "core": {k: color(v) for k, v in CORE.items()},
        "dark": themed(dark),
        "light": themed(light),
    },
    "font": {
        "family": {
            "sans": {"$type": "fontFamily", "$value": ["Space Grotesk", "ui-sans-serif", "system-ui", "sans-serif"]},
            "mono": {"$type": "fontFamily", "$value": ["JetBrains Mono", "ui-monospace", "SFMono-Regular", "Menlo", "monospace"]},
        },
        "scale": {
            n: {"$type": "typography", "$value": {
                "fontFamily": "{font.family.%s}" % fam, "fontSize": f"{size}px", "fontWeight": w,
                "lineHeight": lh, "letterSpacing": tr(t), **({"textTransform": tt} if tt else {})}}
            for n, fam, size, lh, t, w, tt in SCALE
        },
    },
    "space": {str(v): {"$type": "dimension", "$value": f"{v}px"} for v in SPACE},
    "radius": {k: {"$type": "dimension", "$value": v} for k, v in RADIUS.items()},
    "motion": {
        "ease": {"out": {"$type": "cubicBezier", "$value": [0.16, 1, 0.3, 1]}},
        "duration": {k: {"$type": "duration", "$value": f"{v}ms"} for k, v in DUR.items()},
    },
}
open(os.path.join(kit, "tokens", "tokens.json"), "w").write(json.dumps(tokens, indent=2) + "\n")

# ---------- tailwind.preset.js ----------
sem = [k for k in dark if k != "color-scheme" and not k.startswith("mark-") and k != "hatch"]
semantic = ",\n".join(f"        '{k}': 'var(--{k})'" for k in sem)
core = ",\n".join(f"        '{k}': '{v}'" for k, v in CORE.items())
fs_lines = ",\n".join(
    f"        '{n}': ['{size}px', {{ lineHeight: '{lh:g}', letterSpacing: '{tr(t)}', fontWeight: '{w}' }}]"
    for n, fam, size, lh, t, w, tt in SCALE)
space = ",\n".join(f"        'nv-{v}': '{v}px'" for v in SPACE)
js = f"""// NOVA Tailwind preset (Tailwind v3 `presets`, or v4 via `@config`). Generated by _build/build_tokens.py.
// Semantic colours read the CSS variables from tokens.css, so import tokens.css once globally and
// they follow dark/light automatically (no `dark:` variants needed). `nova.*` are the fixed core swatches.
// Usage: module.exports = {{ presets: [require('./brand-kit/tokens/tailwind.preset.js')], content: [...] }}
/** @type {{import('tailwindcss').Config}} */
module.exports = {{
  theme: {{
    extend: {{
      colors: {{
        nova: {{
{core}
        }},
{semantic},
        'mark-frame': 'var(--mark-frame)',
        'mark-star': 'var(--mark-star)'
      }},
      fontFamily: {{
        sans: ['Space Grotesk', 'ui-sans-serif', 'system-ui', 'sans-serif'],
        mono: ['JetBrains Mono', 'ui-monospace', 'SFMono-Regular', 'Menlo', 'monospace']
      }},
      fontSize: {{
{fs_lines}
      }},
      // Labels are mono, 11px, uppercase: use `font-mono text-label uppercase`.
      // Brand spacing steps are prefixed so they don't change Tailwind's numeric scale: p-nv-24, gap-nv-48.
      spacing: {{
{space}
      }},
      borderRadius: {{
        none: '0',
        sm: '2px',
        DEFAULT: '2px',
        full: '9999px'
      }},
      transitionTimingFunction: {{
        nova: '{EASE}',
        DEFAULT: '{EASE}'
      }},
      transitionDuration: {{
        fast: '120ms',
        base: '250ms',
        slow: '400ms',
        slower: '800ms'
      }}
    }}
  }}
}};
"""
open(os.path.join(kit, "tokens", "tailwind.preset.js"), "w").write(js)
print("tokens ok", len(dark), len(light))
